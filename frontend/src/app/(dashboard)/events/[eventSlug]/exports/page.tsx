"use client";

import { useMutation, useQueryClient } from "@tanstack/react-query";
import { Download, FileSpreadsheet, FileText } from "lucide-react";
import { useEffect, useRef, useState } from "react";
import { toast } from "sonner";
import { ManagementErrorState } from "@/components/management/management-error-state";
import { ManagementPageHeader } from "@/components/management/management-page-header";
import { useApiClient } from "@/components/providers/api-client-provider";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import type { DownloadedFile } from "@/lib/api/client";
import type { ExportDataset, ExportFormat } from "@/lib/api/contracts";
import { managementKeys } from "@/lib/api/query-keys";
import { useEventSlugParam } from "@/lib/management/route-params";
import { safeDownloadFilename, triggerBrowserDownload } from "@/lib/operations/download";
import { parseDownloadedFile } from "@/lib/operations/validation";

type ExportRequest = { dataset: ExportDataset; format: ExportFormat };
type ExportResult = { request: ExportRequest; file: DownloadedFile };

const DATASETS: ReadonlyArray<{ id: ExportDataset; label: string; description: string }> = [
  {
    id: "attendees",
    label: "Attendees",
    description: "All authorized attendee records for this event, generated by the backend.",
  },
  {
    id: "checkins",
    label: "Check-ins",
    description: "All authorized check-in records for this event, generated by the backend.",
  },
];

const FORMATS: ReadonlyArray<{ id: ExportFormat; label: string }> = [
  { id: "csv", label: "CSV" },
  { id: "xlsx", label: "XLSX" },
];

function requestKey(request: ExportRequest): string {
  return `${request.dataset}.${request.format}`;
}

export default function ExportsPage() {
  const slug = useEventSlugParam();

  // Remount on event change so in-flight downloads and result state are never
  // reused for a different event.
  return <ExportsWorkspace key={slug} slug={slug} />;
}

function ExportsWorkspace({ slug }: { slug: string }) {
  const api = useApiClient();
  const queryClient = useQueryClient();
  const downloadControllerRef = useRef<AbortController | null>(null);
  const busyRequestRef = useRef<string | null>(null);
  const [busyKey, setBusyKey] = useState<string | null>(null);
  const [result, setResult] = useState<ExportResult | null>(null);

  useEffect(
    () => () => {
      downloadControllerRef.current?.abort();
      downloadControllerRef.current = null;
      busyRequestRef.current = null;
    },
    [],
  );

  const downloadMutation = useMutation({
    mutationFn: async (request: ExportRequest) => {
      const controller = new AbortController();
      downloadControllerRef.current = controller;

      const raw = await api.exports.download(
        slug,
        request.dataset,
        request.format,
        controller.signal,
      );
      const file = parseDownloadedFile(raw, request.format);
      if (!file) {
        throw new Error("The server returned an unexpected export response.");
      }

      triggerBrowserDownload(file);
      return file;
    },
    onSuccess: async (file, request) => {
      await queryClient.invalidateQueries({ queryKey: managementKeys.auditLogsAll(slug) });
      setResult({ request, file });
      toast.success(`${request.dataset} ${request.format.toUpperCase()} export downloaded`, {
        description: safeDownloadFilename(file.filename),
      });
    },
    onSettled: () => {
      downloadControllerRef.current = null;
      busyRequestRef.current = null;
      setBusyKey(null);
    },
  });

  function handleDownload(request: ExportRequest) {
    const key = requestKey(request);
    if (busyRequestRef.current || downloadMutation.isPending) {
      return;
    }

    busyRequestRef.current = key;
    setBusyKey(key);
    void downloadMutation.mutateAsync(request).catch(() => {
      // Displayed by the page-level mutation error state.
    });
  }

  return (
    <div className="space-y-6">
      <ManagementPageHeader
        eyebrow={`Event · ${slug}`}
        title="Data exports"
        description="Download backend-generated attendance data. The browser never assembles or filters export contents."
        backHref={`/events/${encodeURIComponent(slug)}`}
        backLabel="Event"
      />

      <Card>
        <CardHeader>
          <CardTitle>Backend-generated exports</CardTitle>
          <CardDescription>
            The export endpoints expose no query filters or parameters. Each file contains all
            records the backend authorizes for this event, with spreadsheet-safe cell encoding.
          </CardDescription>
        </CardHeader>
        <CardContent>
          <div className="grid gap-4 lg:grid-cols-2">
            {DATASETS.map((dataset) => (
              <Card key={dataset.id}>
                <CardHeader>
                  <CardTitle className="flex items-center gap-2 text-base">
                    <FileSpreadsheet className="h-4 w-4 text-muted-foreground" aria-hidden="true" />
                    {dataset.label}
                  </CardTitle>
                  <CardDescription>{dataset.description}</CardDescription>
                </CardHeader>
                <CardContent className="flex flex-wrap gap-3">
                  {FORMATS.map((format) => {
                    const key = requestKey({ dataset: dataset.id, format: format.id });
                    const isBusy = busyKey === key;

                    return (
                      <Button
                        key={format.id}
                        type="button"
                        variant="outline"
                        size="sm"
                        disabled={busyKey !== null}
                        aria-label={`Download ${dataset.label.toLowerCase()} ${format.label}`}
                        onClick={() =>
                          handleDownload({ dataset: dataset.id, format: format.id })
                        }
                      >
                        {isBusy ? (
                          <Download className="h-3.5 w-3.5 animate-spin" aria-hidden="true" />
                        ) : format.id === "csv" ? (
                          <FileText className="h-3.5 w-3.5" aria-hidden="true" />
                        ) : (
                          <FileSpreadsheet className="h-3.5 w-3.5" aria-hidden="true" />
                        )}
                        {isBusy ? "Preparing…" : format.label}
                      </Button>
                    );
                  })}
                </CardContent>
              </Card>
            ))}
          </div>
        </CardContent>
      </Card>

      {downloadMutation.isError ? (
        <ManagementErrorState error={downloadMutation.error} />
      ) : null}

      {result ? (
        <Alert role="status">
          <AlertTitle>Export ready</AlertTitle>
          <AlertDescription>
            Saved <span className="font-mono">{safeDownloadFilename(result.file.filename)}</span> ·{" "}
            {result.file.contentType} · {result.file.blob.size} bytes.
          </AlertDescription>
        </Alert>
      ) : null}
    </div>
  );
}
